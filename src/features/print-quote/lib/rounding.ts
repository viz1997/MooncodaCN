/**
 * 计价取整 —— **一律向上取整到分**
 *
 * ## 为什么向上取整(2026-11-08)
 *
 * 工作室的要求:**「计价需要向上取整」**。
 *
 * 四舍五入在**期望上**是零和的 —— 一批活里有的多收一分、有的少收一分,
 * 长期看是平的。但工作室要的是**每一单都不低于算出来的那个数**:少收的
 * 那一分钱是真金白银的亏损,而且活越碎越明显(十单各少一分 = 一毛)。
 *
 * 向上取整的口径一句话说得清:**「我们收的钱,一律向上取整到分」**。
 *
 * ## 适用范围
 *
 * **用户付的每一笔钱**:克重费 / 后处理费 / 支撑加价 / 交期加价。
 *
 * **不包括**后台配的那些单价(`pricing-settings.ts` 里的每克单价、后处理
 * 费)—— 那些是工作室自己填的整数分,不是算出来的,没什么可「取整」的。
 *
 * ## 浮点陷阱(必须带 epsilon)
 *
 * `Math.ceil(1.1 * 100)` = **111** —— 因为 `1.1 × 100` 在 IEEE754 下是
 * `110.00000000000001`,多出来的那一丝被向上取整吃掉了。**白多收一分。**
 *
 * 所以减一个极小的 epsilon 再取整:
 *
 * ```
 * Math.ceil(1.1 * 100 - 1e-9) = 110 ✓
 * Math.ceil(0.07 * 100 - 1e-9) = 7 ✓   (0.07 × 100 = 7.000000000000001)
 * ```
 *
 * epsilon 取 **1e-9 分** —— 真实的小数部分最小是 0.01 分,epsilon 比它小
 * 七个数量级,**绝不会把「真有零头」当成「没有零头」**。
 *
 * ## 纯函数,零依赖
 *
 * 客户端(打印单上的档位预览)和服务端(算价)读的是**同一份**实现 ——
 * 两边各写一遍迟早漂移(前端显示 ¥5.58、后端收 ¥5.59)。
 */

/** epsilon —— 分的单位。见文件头的浮点陷阱一节 */
const EPSILON = 1e-9;

/**
 * 向上取整到分
 *
 * 入参**已经是分**(可能是小数)—— 比如「元 × 100」或者「分 × 比例」的
 * 结果。返回整数分。
 */
export function ceilCents(cents: number): number {
  if (!Number.isFinite(cents)) return cents;
  const result = Math.ceil(cents - EPSILON);
  /**
   * `-0` 归一化成 `0`
   *
   * `Math.ceil(-1e-9)` = **-0** —— `0 - EPSILON` 是个极小的负数,向上取整
   * 落在 0 上,符号却留着。`-0 === 0` 为真,但 `Object.is(-0, 0)` 为假 ——
   * 落库、序列化、单元断言都当它是另一个数。归一化掉。
   */
  return result === 0 ? 0 : result;
}

/**
 * 元 → 分,向上取整
 *
 * 报价引擎内部算的是**元**(浮点),边界上换成**分**时走这里。
 */
export function yuanToCentsCeil(yuan: number): number {
  if (!Number.isFinite(yuan)) return yuan;
  return ceilCents(yuan * 100);
}
